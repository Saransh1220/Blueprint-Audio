function producer(handle: string): CatalogProducerSummary {
  return {
    id: `producer-${handle.replace('.', '-')}`,
    handle,
    displayName: producerNames[handle] ?? handle,
    avatarUrl: null,
    avatarFallback: handle.charAt(0),
    isVerified: handle === 'kita.sol',
  };
}

function slugify(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function waveform(seed: number): readonly number[] {
  return Array.from({ length: 22 }, (_, index) =>
    Math.round(20 + Math.abs(Math.sin(seed * (index + 1) * 0.7)) * 75),
  );
}

